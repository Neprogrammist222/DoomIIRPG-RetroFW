with zipfile.ZipFile(ipa_path, "r") as z:
    for fname in fonts:
        raw = bytearray(z.read("Payload/Doom2rpg.app/Packages/" + fname))
        px_off = next(iter(struct.unpack_from("<I", raw, 10)))
        w, h = struct.unpack_from("<ii", raw, 18)
        stride = (w + 3) & ~3
        cw, ch = w // 16, h // 9

        def get_px(x, y):
            return raw.__getitem__(px_off + (h - 1 - y) * stride + x)

        def set_px(x, y, val):
            raw.__setitem__(px_off + (h - 1 - y) * stride + x, val)

        hx, hy = 7 * cw, 2 * ch
        bg = get_px(hx, hy)

        # Собираем используемые в ячейке 'H' цвета и их яркость из RGB-палитры BMP (смещение 54)
        used = set()
        for yy in range(hy, hy + ch):
            for xx in range(hx, hx + cw):
                v = get_px(xx, yy)
                if v != bg:
                    used.add(v)

        def luma(idx):
            b, g, r, _ = struct.unpack_from("<BBBB", raw, 54 + idx * 4)
            return r + g + b

        sorted_colors = sorted(used, key=luma)
        darkest = sorted_colors.__getitem__(0) if sorted_colors else 15
        brightest = sorted_colors.__getitem__(-1) if sorted_colors else 1

        if "Dark" in fname:
            fg = darkest
            outline = bg
        else:
            fg = brightest
            outline = darkest

        for slot, char in zip(SLOTS, CHARS):
            col, row = slot % 16, slot // 16
            bx, by = col * cw, row * ch
            for yy in range(by, by + ch):
                for xx in range(bx, bx + cw):
                    set_px(xx, yy, bg)
            glyph = GLYPHS.get(char)
            sx = max(1, cw // 9)
            sy = max(1, (ch - 4) // 10)
            ox = bx + max(1, (cw - 7 * sx) // 2)
            oy = by + max(2, (ch - 10 * sy) // 2)
            if outline != bg and outline != fg:
                for gy, line in enumerate(glyph):
                    for gx, bit in enumerate(line):
                        if bit == "1":
                            for dy in range(-1, sy + 1):
                                for dx in range(-1, sx + 1):
                                    px, py = ox + gx * sx + dx, oy + gy * sy + dy
                                    if bx <= px < bx + cw and by <= py < by + ch:
                                        set_px(px, py, outline)
            for gy, line in enumerate(glyph):
                for gx, bit in enumerate(line):
                    if bit == "1":
                        for dy in range(sy):
                            for dx in range(sx):
                                px, py = ox + gx * sx + dx, oy + gy * sy + dy
                                if bx <= px < bx + cw and by <= py < by + ch:
                                    set_px(px, py, fg)

        with open("ru_patch/" + fname, "wb") as out:
            out.write(raw)
        print(f"OK {fname}: bg={bg}, fg={fg} (luma={luma(fg)}), outline={outline}")
